import Foundation

/// A validation failure, with the same codes as the shared catalog vectors (`ui-catalog-vectors.json`).
public struct UIIssue: Sendable, Equatable {
    public let path: String
    public let code: String
}

/// The closed component set a dashboard layout may use (`contracts/foundation/ui-catalog.json`) and the check
/// that a layout stays inside it. A port of `validateSpec` in DAD-Main `scripts/ui-catalog.mjs`: both must give
/// the shared vectors the same verdicts.
public struct UICatalog: Sendable {
    struct Prop: Sendable {
        let kind: String
        let max: String?
        let target: String?
        let values: [String]
        let allowed: [String]
    }
    struct Component: Sendable {
        let props: [String: Prop]
        let required: [String]
        let exactlyOneOf: [String]
    }

    /// The catalog version this build draws; a layout written for any other is not shown.
    public let version: Int
    let limits: [String: Int]
    let formats: Set<String>
    let captions: [String: String]
    let labels: [String: String]
    let allowedPaths: Set<String>
    let components: [String: Component]
    /// Every pointer into the DonorDashboard response mapped to its schema kind (generated by `prepare-client.mjs`).
    let binds: [String: String]

    /// nil when the bundled catalog cannot be read, in which case no panel is ever shown.
    public static let shared: UICatalog? = {
        guard let catalog = Bundle.module.url(forResource: "ui-catalog", withExtension: "json"),
              let links = Bundle.module.url(forResource: "links", withExtension: "json"),
              let binds = Bundle.module.url(forResource: "ui-binds", withExtension: "json"),
              let data = try? [catalog, links, binds].map({ try Data(contentsOf: $0) }) else { return nil }
        return try? UICatalog(catalog: data[0], links: data[1], binds: data[2])
    }()

    public init(catalog: Data, links: Data, binds: Data) throws {
        let root = try UIValue(json: catalog), linkRoot = try UIValue(json: links)
        guard let version = root["catalog_version"]?.integerValue, let limits = root["limits"]?.objectValue,
              let formats = root["formats"]?.objectValue, let captions = root["metric_captions"]?.objectValue,
              let navigate = root["navigate"], let labels = navigate["labels"]?.objectValue,
              let lists = navigate["path_lists"]?.arrayValue, let components = root["components"]?.objectValue,
              let kinds = try UIValue(json: binds).objectValue else { throw AccountError.invalidConfiguration }
        self.version = version
        self.limits = limits.compactMapValues(\.integerValue)
        self.formats = Set(formats.keys)
        self.captions = captions.compactMapValues(\.stringValue)
        self.labels = labels.compactMapValues(\.stringValue)
        allowedPaths = Set(lists.compactMap(\.stringValue).flatMap { linkRoot[$0]?.arrayValue?.compactMap(\.stringValue) ?? [] })
        self.components = components.compactMapValues { definition in
            guard let props = definition["props"]?.objectValue else { return nil }
            return Component(
                props: props.mapValues { prop in
                    Prop(kind: prop["kind"]?.stringValue ?? "", max: prop["max"]?.stringValue,
                         target: prop["target"]?.stringValue,
                         values: prop["values"]?.arrayValue?.compactMap(\.stringValue) ?? [],
                         allowed: prop["allowed"]?.arrayValue?.compactMap(\.stringValue) ?? [])
                },
                required: definition["required"]?.arrayValue?.compactMap(\.stringValue) ?? [],
                exactlyOneOf: definition["exactly_one_of"]?.arrayValue?.compactMap(\.stringValue) ?? [])
        }
        self.binds = kinds.compactMapValues(\.stringValue)
    }

    // MARK: Text policy

    private static let schemeLike = try! NSRegularExpression(
        pattern: #"(?:^|[^a-z0-9])(?:[a-z][a-z0-9+.-]{1,30}://|(?:https?|javascript|data|mailto|tel|sms|file|ftp|blob|vbscript):|www\.)"#,
        options: [.caseInsensitive])
    private static let markdownLink = try! NSRegularExpression(
        pattern: #"\]\s*\(|\]\s*\[|^\s*\[[^\]]*\]:\s"#, options: [.anchorsMatchLines])

    static func labelProblem(_ value: UIValue?) -> String? {
        guard let text = value?.stringValue else { return "BAD_TYPE" }
        if text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty { return "LABEL_EMPTY" }
        let bad: Set<Unicode.GeneralCategory> = [.control, .format, .lineSeparator, .paragraphSeparator]
        if text.contains(where: { $0 == "<" || $0 == ">" }) || text.unicodeScalars.contains(where: { bad.contains($0.properties.generalCategory) }) {
            return "LABEL_CONTENT"
        }
        let range = NSRange(text.startIndex..., in: text)
        if schemeLike.firstMatch(in: text, range: range) != nil || markdownLink.firstMatch(in: text, range: range) != nil {
            return "LABEL_CONTENT"
        }
        return nil
    }

    // MARK: Binds

    /// The segments of an RFC 6901 pointer, or nil when it is malformed.
    static func segments(_ pointer: String) -> [String]? {
        guard pointer.hasPrefix("/") else { return nil }
        let parts = pointer.dropFirst().split(separator: "/", omittingEmptySubsequences: false).map(String.init)
        for part in parts {
            if part.isEmpty || part.hasSuffix("~") { return nil }
            var rest = Substring(part)
            while let tilde = rest.firstIndex(of: "~") {
                let next = rest.index(after: tilde)
                guard next < rest.endIndex, rest[next] == "0" || rest[next] == "1" else { return nil }
                rest = rest[rest.index(after: next)...]
            }
        }
        return parts.map { $0.replacingOccurrences(of: "~1", with: "/").replacingOccurrences(of: "~0", with: "~") }
    }

    private static let scalarKinds: Set<String> = ["string", "integer", "number", "boolean"]

    // MARK: Validation

    public func validate(_ spec: UIValue) -> [UIIssue] {
        var run = Run(catalog: self)
        guard case .array(let blocks) = spec else { return [UIIssue(path: "", code: "SPEC_NOT_ARRAY")] }
        if blocks.isEmpty { return [UIIssue(path: "", code: "SPEC_EMPTY")] }
        for (index, block) in blocks.enumerated() { run.node(block, "/\(index)", depth: 1) }
        return run.issues
    }

    private struct Run {
        let catalog: UICatalog
        var issues: [UIIssue] = []
        var nodes = 0
        var nodeLimitReported = false
        var counted: Set<String> = []

        init(catalog: UICatalog) { self.catalog = catalog }

        mutating func fail(_ path: String, _ code: String) { issues.append(UIIssue(path: path, code: code)) }

        mutating func count(_ path: String) {
            counted.insert(path)
            nodes += 1
            if nodes > catalog.limits["max_nodes", default: 0], !nodeLimitReported {
                nodeLimitReported = true
                fail(path, "TOO_MANY_NODES")
            }
        }

        mutating func bind(_ path: String, _ value: UIValue?, target: String) {
            guard let pointer = value?.stringValue else { return fail(path, "BAD_TYPE") }
            guard let parts = UICatalog.segments(pointer) else { return fail(path, "BIND_SYNTAX") }
            // A layout never binds to itself, which would put its own literal text into a bind-only prop.
            guard parts.first != "insights", let kind = catalog.binds[pointer] else { return fail(path, "BIND_UNRESOLVED") }
            if target == "array" {
                if kind != "array" { fail(path, "BIND_NOT_ARRAY") }
            } else if !UICatalog.scalarKinds.contains(kind) {
                fail(path, "BIND_NOT_SCALAR")
            } else if target == "integer", kind != "integer" {
                fail(path, "BIND_NOT_INTEGER")
            }
        }

        mutating func prop(_ path: String, _ name: String, _ definition: Prop, _ value: UIValue, component: String) {
            let at = "\(path)/\(name)"
            switch definition.kind {
            case "label":
                if let problem = UICatalog.labelProblem(value) { return fail(at, problem) }
                if let limit = definition.max.flatMap({ catalog.limits[$0] }), (value.stringValue ?? "").unicodeScalars.count > limit {
                    fail(at, "LABEL_TOO_LONG")
                }
            case "bind": bind(at, value, target: definition.target ?? "scalar")
            case "enum":
                guard let text = value.stringValue else { return fail(at, "BAD_TYPE") }
                if !definition.values.contains(text) { fail(at, "BAD_ENUM") }
            case "format":
                guard let text = value.stringValue else { return fail(at, "BAD_TYPE") }
                if !catalog.formats.contains(text) { fail(at, "BAD_FORMAT") }
            case "caption":
                guard let text = value.stringValue else { return fail(at, "BAD_TYPE") }
                if catalog.captions[text] == nil { fail(at, "BAD_CAPTION") }
            case "navigate":
                guard let text = value.stringValue else { return fail(at, "BAD_TYPE") }
                if !catalog.allowedPaths.contains(text) { fail(at, "NAV_FORBIDDEN") }
            case "children": children(at, value, definition, component: component)
            default: break
            }
        }

        mutating func children(_ at: String, _ value: UIValue, _ definition: Prop, component: String) {
            guard let items = value.arrayValue else { return fail(at, "BAD_TYPE") }
            if items.isEmpty { return fail(at, "CHILDREN_EMPTY") }
            if let limit = definition.max.flatMap({ catalog.limits[$0] }), items.count > limit {
                fail(at, component == "MetricGrid" ? "GRID_TOO_LARGE" : "LIST_TOO_LARGE")
            }
            for (index, child) in items.enumerated() {
                let childPath = "\(at)/\(index)"
                if let type = child["type"]?.stringValue, catalog.components[type] != nil {
                    count(childPath)
                    if !definition.allowed.contains(type) {
                        fail(childPath, "CHILD_NOT_ALLOWED")
                        if child["children"]?.arrayValue != nil { fail("\(childPath)/children", "TOO_DEEP") }
                        continue
                    }
                }
                node(child, childPath, depth: 2)
            }
        }

        mutating func node(_ value: UIValue, _ path: String, depth: Int) {
            if !counted.contains(path) { count(path) }
            guard let object = value.objectValue else { return fail(path, "NODE_INVALID") }
            guard let type = object["type"]?.stringValue, !type.isEmpty else { return fail(path, "MISSING_TYPE") }
            // An unknown type is valid and draws nothing, so a newer layout degrades on an older app.
            guard let definition = catalog.components[type] else { return }
            if depth > catalog.limits["max_depth", default: 0] { return fail(path, "TOO_DEEP") }
            for key in object.keys where key != "type" && definition.props[key] == nil { fail("\(path)/\(key)", "UNKNOWN_PROP") }
            for name in definition.required where object[name] == nil { fail("\(path)/\(name)", "MISSING_PROP") }
            if !definition.exactlyOneOf.isEmpty, definition.exactlyOneOf.filter({ object[$0] != nil }).count != 1 {
                fail(path, "ONE_OF")
            }
            for (name, definitionProp) in definition.props.sorted(by: { $0.key < $1.key }) {
                if let propValue = object[name] { prop(path, name, definitionProp, propValue, component: type) }
            }
        }
    }
}
